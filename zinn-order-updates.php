/**
 * The Zinn® API base. A filter, so a staging install can point elsewhere.
 */
function zinn_order_updates_api_base(): string {
	/**
	 * Filters the Zinn® API base URL.
	 *
	 * @param string $base The API base, no trailing slash.
	 */
	return rtrim( (string) apply_filters( 'zinn_order_updates_api_base', 'https://api.zinndigital.com' ), '/' );
}

/**
 * The Zinn® dashboard base, where the store owner approves the connection.
 */
function zinn_order_updates_app_base(): string {
	/**
	 * Filters the Zinn® dashboard base URL.
	 *
	 * @param string $base The dashboard base, no trailing slash.
	 */
	return rtrim( (string) apply_filters( 'zinn_order_updates_app_base', 'https://app.zinndigital.com' ), '/' );
}

